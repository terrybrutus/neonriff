import type { Difficulty, Lane, Note, Song, SongStyle } from "@/types/game";

let _noteIdCounter = 0;

function makeNote(
  lane: Lane,
  time: number,
  type: Note["type"] = "tap",
  holdDuration?: number,
): Note {
  return {
    id: `n${_noteIdCounter++}`,
    lane,
    time,
    type,
    holdDuration,
    hit: false,
    missed: false,
  };
}

// Pattern strings: "01234" chars = lanes to hit on that beat subdivision
// Each entry = 1/8th note subdivision
// Use "_" for rest
function buildChart(
  bpm: number,
  patterns: string[],
  startOffset = 1.5,
  density: "sparse" | "normal" | "dense" | "insane" = "normal",
): Note[] {
  _noteIdCounter = 0;
  const beatDur = 60 / bpm;
  const subDur = beatDur / 2; // 8th note
  const notes: Note[] = [];

  const densityFilter: Record<
    typeof density,
    (i: number, lane: number) => boolean
  > = {
    sparse: (i, l) => (i % 2 === 0 && l % 2 === 0) || i % 4 === 0,
    normal: () => true,
    dense: () => true,
    insane: () => true,
  };

  patterns.forEach((pat, subIdx) => {
    const time = startOffset + subIdx * subDur;
    for (const char of pat) {
      const lane = Number.parseInt(char) as Lane;
      if (Number.isNaN(lane) || lane < 0 || lane > 4) continue;
      if (density === "sparse" && !densityFilter.sparse(subIdx, lane)) continue;
      notes.push(makeNote(lane, time));
    }
  });

  return notes;
}

